"use client";

import { useEffect, useState } from "react";

type Alert = {
  alert_id: number;
  incident_id: number;
  alert_type: string;
  message: string;
  severity: string;
  is_read: number;
  created_at: string;
  incident_title: string;
};

export default function AlertsPage() {
  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [error, setError] = useState("");

  useEffect(() => {
    fetch("/api/incidents")
      .then((res) => res.json())
      .then((data) => setAlerts(data.alerts || []))
      .catch(() => setError("Unable to load alerts."));
  }, []);

  return (
    <main className="min-h-screen bg-slate-950 p-6 text-slate-100">
      <div className="mx-auto max-w-6xl">
        <h1 className="text-2xl font-bold">Security Alerts</h1>
        <p className="mt-2 text-sm text-slate-400">
          Review alerts generated by IOC correlation.
        </p>

        {error && <p className="mt-4 text-rose-400">{error}</p>}

        <div className="mt-6 space-y-3">
          {alerts.map((alert) => (
            <div
              key={alert.alert_id}
              className="rounded-xl border border-slate-800 bg-slate-900 p-4"
            >
              <div className="flex justify-between gap-3">
                <h2 className="font-semibold">{alert.alert_type}</h2>
                <span className="text-sm text-slate-400">
                  {alert.is_read ? "Read" : "Unread"}
                </span>
              </div>

              <p className="mt-2 text-sm text-slate-300">{alert.message}</p>
              <p className="mt-2 text-xs text-slate-400">
                Incident #{alert.incident_id} — {alert.incident_title}
              </p>
              <p className="mt-1 text-xs text-slate-500">
                Severity: {alert.severity} · {alert.created_at}
              </p>
            </div>
          ))}

          {alerts.length === 0 && !error && (
            <p className="text-sm text-slate-400">No alerts found.</p>
          )}
        </div>
      </div>
    </main>
  );
}